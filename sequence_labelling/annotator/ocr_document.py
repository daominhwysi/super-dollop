#!/usr/bin/env python3
"""
ocr_document.py — Unified Robust OCR Document & Page Model for Vietnamese Sequence Labelling.

Provides an authoritative, fault-tolerant data model and parser for OCR examination markdown.
Eliminates all page-boundary anomalies:
1. Mismatched or missing </page> closing tags (pages terminating directly at next <page> or EOF).
2. Unclosed <page_metadata> blocks (terminated at </page>, next <page>, or EOF).
3. Redundant or stray </page> / </pages> tags.
4. Malformed page opening markers (e.g., `<page\\n` without closing `>`).
5. Preamble/postamble text located outside page boundary tags.
6. Legacy comment metadata (`<!-- PAGE_METADATA_START ... -->`).
7. Completely unpaged plain Markdown documents.
8. Monotonic 1-based page numbering and exact global offset alignment matching SourceMerger.
"""

from __future__ import annotations

import json
import logging
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple, Union

logger = logging.getLogger("ocr_document")

PAGE_SEPARATOR = "\n\n"


@dataclass
class OCRPage:
    """Represents a single page extracted from OCR markdown."""

    p: int
    text: str
    meta: Dict[str, Any] = field(default_factory=dict)
    raw_content: str = ""
    global_start: int = 0
    global_end: int = 0
    estimated_tokens: int = 0
    lines_count: int = 0
    is_blank: bool = False

    def to_chunk_page(self) -> Dict[str, Any]:
        """
        Formats into the exact dictionary schema consumed by greedy_oversize_chunker
        and build_chunk_plan.
        """
        return {
            "p": self.p,
            "text": self.text,
            "meta": self.meta,
            "metadata": self.meta,
            "raw_content": self.raw_content,
            "estimated_tokens": max(50, self.estimated_tokens),
            "head": self.meta.get("head", "CLEAN"),
            "tail": self.meta.get("tail", "CLEAN"),
            "global_start": self.global_start,
            "global_end": self.global_end,
            "lines_count": self.lines_count,
        }

    @property
    def page_number(self) -> int:
        return self.p

    @property
    def cleaned_text(self) -> str:
        return self.text

    @property
    def raw_text(self) -> str:
        return self.raw_content

    @property
    def metadata(self) -> Dict[str, Any]:
        return self.meta

    def to_markdown(self, include_metadata: bool = True) -> str:
        """Serializes this page into standard canonical XML markdown."""
        parts = ["<page>"]
        if self.text.strip():
            parts.append(self.text.strip())

        if include_metadata and self.meta:
            meta_json = json.dumps(self.meta, ensure_ascii=False, indent=2)
            parts.append(f"\n<page_metadata>\n{meta_json}\n</page_metadata>")

        parts.append("</page>")
        return "\n".join(parts)


@dataclass
class OCRDocument:
    """Authoritative container representing a complete examination OCR document."""

    doc_id: str
    pages: List[OCRPage]
    raw_text: str = ""
    metadata_stream: List[Dict[str, Any]] = field(default_factory=list)
    diagnostics: Dict[str, Any] = field(default_factory=dict)

    @property
    def total_pages(self) -> int:
        return len(self.pages)

    @property
    def clean_text(self) -> str:
        """
        Unified document text joined with PAGE_SEPARATOR ("\\n\\n").
        Matches the exact canonical text generated by SourceMerger (_build_page_canonical).
        """
        return PAGE_SEPARATOR.join(p.text for p in self.pages)

    @property
    def raw_cleaned_text(self) -> str:
        """
        Full raw document text with all page wrapper tags (<page>, </page>, <pages>, </pages>)
        and <page_metadata> blocks stripped. Used for character fidelity verification.
        """
        return strip_page_markup(self.raw_text)

    @property
    def page_numbers(self) -> List[int]:
        return [p.p for p in self.pages]

    def get_page(self, page_number: int) -> Optional[OCRPage]:
        """Retrieves page by 1-based page number."""
        for p in self.pages:
            if p.p == page_number:
                return p
        return None

    def to_chunk_pages(self) -> List[Dict[str, Any]]:
        """Returns the list of page dictionaries ready for greedy_oversize_chunker."""
        return [p.to_chunk_page() for p in self.pages]

    def verify_character_fidelity(
        self, annotated_xml: str, ignore_whitespace: bool = True
    ) -> Dict[str, Any]:
        """
        Verifies 100% character preservation between this document and parsed/annotated XML.
        Strips XML annotations and compares against clean document text.
        """
        # Strip XML annotation tags (retaining content)
        stripped = re.sub(r"<[^>]+>", "", annotated_xml)

        if ignore_whitespace:
            norm_stripped = re.sub(r"\s+", "", stripped)
            norm_doc = re.sub(r"\s+", "", self.clean_text)
            norm_raw = re.sub(r"\s+", "", self.raw_cleaned_text)
            match_doc = (norm_stripped == norm_doc)
            match_raw = (norm_stripped == norm_raw)
            is_match = match_doc or match_raw
            mismatch_char_diff = abs(len(norm_stripped) - len(norm_doc))
        else:
            is_match = (stripped.strip() == self.clean_text.strip())
            mismatch_char_diff = abs(len(stripped) - len(self.clean_text))

        result = {
            "is_exact_match": is_match,
            "stripped_length": len(stripped),
            "clean_doc_length": len(self.clean_text),
            "raw_cleaned_length": len(self.raw_cleaned_text),
            "mismatch_char_diff": mismatch_char_diff,
        }

        if not is_match:
            # Provide sample diagnostic context where discrepancy occurs
            norm_s = re.sub(r"\s+", "", stripped)
            norm_d = re.sub(r"\s+", "", self.clean_text)
            min_l = min(len(norm_s), len(norm_d))
            diff_pos = min_l
            for i in range(min_l):
                if norm_s[i] != norm_d[i]:
                    diff_pos = i
                    break
            s_snip = norm_s[max(0, diff_pos - 30) : min(len(norm_s), diff_pos + 30)]
            d_snip = norm_d[max(0, diff_pos - 30) : min(len(norm_d), diff_pos + 30)]
            result["first_diff_position"] = diff_pos
            result["stripped_diff_snippet"] = s_snip
            result["doc_diff_snippet"] = d_snip

        return result

    def to_standard_markdown(self, include_metadata: bool = True) -> str:
        """Standardizes the entire document into canonical XML markdown (<pages><page>...</page></pages>)."""
        rendered_pages = [p.to_markdown(include_metadata=include_metadata) for p in self.pages]
        return f"<pages>\n" + "\n\n".join(rendered_pages) + "\n</pages>\n"

    def save(self, file_path: Union[str, Path], include_metadata: bool = True) -> Path:
        """Writes standardized canonical markdown to disk."""
        target = Path(file_path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(self.to_standard_markdown(include_metadata=include_metadata), encoding="utf-8")
        return target

    @classmethod
    def from_file(
        cls, file_path: Union[str, Path], doc_id: Optional[str] = None
    ) -> "OCRDocument":
        """Loads and parses an OCR markdown document from a file path."""
        p = Path(file_path)
        if not p.exists():
            raise FileNotFoundError(f"OCR markdown file not found: {p}")
        raw = p.read_text(encoding="utf-8")
        resolved_id = doc_id or p.stem
        return cls.from_markdown(raw_text=raw, doc_id=resolved_id)

    @classmethod
    def from_markdown(
        cls, raw_text: str, doc_id: str = "doc"
    ) -> "OCRDocument":
        """
        Parses OCR markdown with fault-tolerant page segmentation.
        Guarantees zero data loss across all real-world tag permutations.
        """
        # 1. Normalize line endings & strip UTF-8 BOM
        text = raw_text.lstrip("\ufeff").replace("\r\n", "\n").replace("\r", "\n")

        # 2. Repair malformed opening tags (e.g. standalone `<page\n` lacking closing `>`)
        text = re.sub(
            r"^[ \t]*<page[ \t]*(?:\n|$)",
            "<page>\n",
            text,
            flags=re.MULTILINE | re.IGNORECASE,
        )

        # 3. Deduplicate consecutive <page> tags with only whitespace between them
        text = re.sub(
            r"(?:<page\b[^>]*>[ \t]*\n?){2,}",
            "<page>\n",
            text,
            flags=re.IGNORECASE,
        )

        # 4. Find page start anchors
        page_matches = list(re.finditer(r"<page\b[^>]*>", text, flags=re.IGNORECASE))
        pages_raw: List[str] = []
        preamble = ""

        if page_matches:
            # Preamble before the first <page>
            raw_preamble = text[: page_matches[0].start()].strip()
            # Strip outer <pages> tag from preamble
            preamble = re.sub(
                r"^\s*<\s*/?\s*pages\b[^>]*>\s*", "", raw_preamble, flags=re.IGNORECASE
            ).strip()

            for i, m in enumerate(page_matches):
                start = m.end()
                end = page_matches[i + 1].start() if i + 1 < len(page_matches) else len(text)
                block = text[start:end]

                # Strip trailing </page> or </pages>
                block = re.sub(r"\s*</page\s*>\s*$", "", block, flags=re.IGNORECASE)
                block = re.sub(r"\s*</pages\s*>\s*$", "", block, flags=re.IGNORECASE)
                pages_raw.append(block)

            # Prepend preamble to first page so no document text is ever lost
            if preamble and pages_raw:
                pages_raw[0] = preamble + "\n\n" + pages_raw[0]
            elif preamble and not pages_raw:
                pages_raw.append(preamble)

        else:
            # Check for legacy comment metadata (<!-- PAGE_METADATA_START ... -->)
            legacy_pattern = re.compile(
                r"<!--\s*PAGE_METADATA_START\s*(.*?)\s*PAGE_METADATA_END\s*-->",
                re.DOTALL,
            )
            legacy_matches = list(legacy_pattern.finditer(text))
            if legacy_matches:
                for i, match in enumerate(legacy_matches):
                    content_start = match.end()
                    content_end = (
                        legacy_matches[i + 1].start()
                        if i + 1 < len(legacy_matches)
                        else len(text)
                    )
                    page_content = text[content_start:content_end]
                    # Include the comment so metadata can be extracted in stage 5
                    pages_raw.append(match.group(0) + "\n" + page_content)
            else:
                # Unpaged document fallback
                clean_body = re.sub(
                    r"^\s*<\s*/?\s*pages\b[^>]*>\s*", "", text.strip(), flags=re.IGNORECASE
                )
                clean_body = re.sub(
                    r"\s*<\s*/?\s*pages\b[^>]*>\s*$", "", clean_body, flags=re.IGNORECASE
                ).strip()
                pages_raw.append(clean_body)

        # 5. Extract metadata and clean body for each page
        parsed_pages: List[OCRPage] = []
        metadata_stream: List[Dict[str, Any]] = []
        global_offset = 0

        for idx, raw_block in enumerate(pages_raw):
            meta = {}
            body = raw_block

            # A. Check <page_metadata> block (closed or unclosed)
            meta_m = re.search(
                r"(?:<\|page_metadata\|>|<page_metadata>)\s*(.*?)\s*(?:<\|end_metadata\|>|</page_metadata>|(?=</page>)|(?=<page\b)|$)",
                raw_block,
                re.DOTALL | re.IGNORECASE,
            )
            if meta_m:
                meta_str = meta_m.group(1).strip()
                # Strip markdown code fences if present in OCR output
                meta_str = re.sub(r"^```(?:json)?\s*", "", meta_str)
                meta_str = re.sub(r"\s*```$", "", meta_str)
                try:
                    meta = json.loads(meta_str)
                except Exception:
                    # Lenient regex fallback for malformed JSON
                    for key in ["p", "w", "h", "head", "tail"]:
                        km = re.search(
                            rf"\"{key}\"\s*:\s*(?:\"([^\"]+)\"|(\d+))", meta_str
                        )
                        if km:
                            val = km.group(1) or km.group(2)
                            meta[key] = int(val) if val.isdigit() else val

                # Slice metadata out of body text
                body = raw_block[: meta_m.start()] + raw_block[meta_m.end() :]

            # B. Check legacy comment metadata
            if not meta and "PAGE_METADATA_START" in body:
                leg_m = re.search(
                    r"<!--\s*PAGE_METADATA_START\s*(.*?)\s*PAGE_METADATA_END\s*-->",
                    body,
                    re.DOTALL,
                )
                if leg_m:
                    try:
                        meta = json.loads(leg_m.group(1).strip())
                    except Exception:
                        pass
                    body = body[: leg_m.start()] + body[leg_m.end() :]

            # C. Clean residual page markup tags from body
            body = re.sub(r"</?page(?:_metadata)?\b[^>]*>", "", body, flags=re.IGNORECASE)
            body = re.sub(r"</?pages\b[^>]*>", "", body, flags=re.IGNORECASE)
            body = re.sub(
                r"<!--\s*PAGE_METADATA_START.*?PAGE_METADATA_END\s*-->",
                "",
                body,
                flags=re.DOTALL,
            )

            clean_text = body.strip()
            is_blank = (len(clean_text) == 0)

            # Monotonic 1-based page number
            p_val = meta.get("p")
            if p_val is not None and str(p_val).isdigit():
                p_num = int(p_val)
            else:
                p_num = idx + 1
                meta["p"] = p_num

            # Compute synchronized global character offsets
            if parsed_pages:
                global_offset += len(PAGE_SEPARATOR)
            start_off = global_offset
            global_offset += len(clean_text)

            tok_count = max(50, len(clean_text.split())) if clean_text else 0
            lines_c = len(clean_text.splitlines()) if clean_text else 0

            page_obj = OCRPage(
                p=p_num,
                text=clean_text,
                meta=meta,
                raw_content=raw_block,
                global_start=start_off,
                global_end=global_offset,
                estimated_tokens=tok_count,
                lines_count=lines_c,
                is_blank=is_blank,
            )

            parsed_pages.append(page_obj)
            metadata_stream.append(meta)

        # 6. Ensure monotonic page numbering if OCR metadata skipped or repeated numbers
        reconciled_pages = _reconcile_page_numbers(parsed_pages)

        return cls(
            doc_id=doc_id,
            pages=reconciled_pages,
            raw_text=raw_text,
            metadata_stream=metadata_stream,
            diagnostics={
                "has_preamble": bool(preamble),
                "total_pages": len(reconciled_pages),
                "blank_pages_count": sum(1 for p in reconciled_pages if p.is_blank),
            },
        )


def _reconcile_page_numbers(pages: List[OCRPage]) -> List[OCRPage]:
    """Ensures page numbers are 1-based, unique, and strictly monotonically increasing."""
    if not pages:
        return []

    # Check if numbers are already strictly monotonic 1..N
    expected = list(range(1, len(pages) + 1))
    current = [p.p for p in pages]

    if current == expected:
        return pages

    # If numbers are duplicate or not contiguous, re-index monotonically while preserving relative order
    seen = set()
    has_duplicates = False
    for p in current:
        if p in seen:
            has_duplicates = True
            break
        seen.add(p)

    if has_duplicates or any(current[i] >= current[i + 1] for i in range(len(current) - 1)):
        logger.warning(
            f"Page numbers were non-monotonic or duplicated: {current[:10]}... Re-indexing to 1..{len(pages)}."
        )
        for idx, page in enumerate(pages, start=1):
            page.p = idx
            page.meta["p"] = idx

    return pages


def strip_page_markup(text: str) -> str:
    """
    Deterministic utility stripping all page boundary tags and metadata blocks.
    Preserves 100% of human/examination textual content.
    """
    if not text:
        return ""

    # 1. Strip page_metadata blocks (both closed and unclosed)
    cleaned = re.sub(
        r"(?:<\|page_metadata\|>|<page_metadata>)\s*.*?(?:<\|end_metadata\|>|</page_metadata>|(?=</page>)|(?=<page\b)|$)",
        "",
        text,
        flags=re.DOTALL | re.IGNORECASE,
    )
    # 2. Strip legacy comment metadata
    cleaned = re.sub(
        r"<!--\s*PAGE_METADATA_START.*?PAGE_METADATA_END\s*-->",
        "",
        cleaned,
        flags=re.DOTALL,
    )
    # 3. Strip <pages>, </pages>, <page ...>, </page>
    cleaned = re.sub(r"</?pages?\b[^>]*>", "", cleaned, flags=re.IGNORECASE)
    return cleaned.strip()


def split_raw_markdown_pages(raw_text: str) -> List[Dict[str, Any]]:
    """
    Drop-in replacement for legacy split_raw_markdown_pages across all scripts.
    Constructs an OCRDocument and returns chunker-ready dictionaries.
    """
    doc = OCRDocument.from_markdown(raw_text)
    return doc.to_chunk_pages()


def extract_page_metadata_stream(full_markdown_text: str) -> List[Dict[str, Any]]:
    """
    Robust drop-in replacement for extract_metadata_headers_from_markdown.
    Extracts all metadata dictionaries from OCR markdown.
    """
    doc = OCRDocument.from_markdown(full_markdown_text)
    return doc.metadata_stream
